#!/usr/bin/env node
// galaxy-brain — A/B result-table generator (SCOPE v2.0 gate: "regenerate the table from one command").
// This is the DETERMINISTIC, quota-free half of the rig. Given per-task, per-arm workdirs that an
// agent has already fixed, it re-derives the blind verdict for each — arm-independent verifier,
// full-suite regression, test-gaming signals, diff size — and prints the result table. The verdict
// is reproduced by a machine, not assembled by hand.
//
// It does NOT call any LLM. Running the arms (the expensive half) is a separate, opt-in step the
// human triggers; this command only judges whatever is already in the arm dirs.
//
// Layout expected under --runs <root>:   <root>/<task>/<arm>/   (each a git repo with a `base` tag)
// Tasks + verifiers are read from eval/tasks/<task>/ (verify_*_test.py, or verify.sh).
//
// Usage:
//   node eval/run.js verify --runs <root> [--python <interp>] [--json]
// Exit codes: 0 = table produced · 2 = usage/setup error. (A failing arm is data, not an error.)

const { spawnSync } = require("node:child_process");
const fs = require("node:fs");
const path = require("node:path");

const REPO = path.resolve(__dirname, "..");
const TASKS_DIR = path.join(__dirname, "tasks");
const TEST_GUARD = path.join(REPO, "scripts", "test-guard.js");

function usage(m) {
  process.stderr.write(m + "\n");
  process.exit(2);
}
function arg(name, fb) {
  const i = process.argv.indexOf(name);
  return i >= 0 && process.argv[i + 1] ? process.argv[i + 1] : fb;
}
const hasFlag = (n) => process.argv.includes(n);

function discoverTasks() {
  if (!fs.existsSync(TASKS_DIR)) usage("no eval/tasks dir");
  return fs
    .readdirSync(TASKS_DIR, { withFileTypes: true })
    .filter((e) => e.isDirectory())
    .map((e) => {
      const dir = path.join(TASKS_DIR, e.name);
      const pyVerifiers = fs.readdirSync(dir).filter((f) => /^verify_.*_test\.py$/.test(f)).map((f) => path.join(dir, f));
      const shVerifier = fs.existsSync(path.join(dir, "verify.sh")) ? path.join(dir, "verify.sh") : null;
      return { name: e.name, pyVerifiers, shVerifier };
    });
}

function py(python, args, cwd, srcOnPath) {
  return spawnSync(python, args, {
    cwd,
    encoding: "utf8",
    maxBuffer: 32 * 1024 * 1024,
    env: { ...process.env, PYTHONPATH: srcOnPath }, // prepend the arm's src so it wins over any editable install
  });
}

function judgeArm(task, armDir, python) {
  const src = path.join(armDir, "src");
  // reward: arm-independent verifier(s) must pass
  let verifierPass = true;
  if (task.pyVerifiers.length) {
    for (const v of task.pyVerifiers) {
      const r = py(python, ["-m", "pytest", v, "-q"], armDir, src);
      if (r.status !== 0) verifierPass = false;
    }
  } else if (task.shVerifier) {
    const r = spawnSync("sh", [task.shVerifier], { cwd: armDir, encoding: "utf8", env: { ...process.env, PYTHONPATH: src } });
    verifierPass = r.status === 0;
  } else {
    verifierPass = null; // no verifier defined
  }
  // suite: full regression must stay green
  const suite = py(python, ["-m", "pytest", "-q"], armDir, src);
  const suiteGreen = suite.status === 0;
  const suiteN = ((suite.stdout || "").match(/(\d+) passed/) || [])[1] || "?";
  // gaming: test-guard over the agent's diff
  const tg = spawnSync("node", [TEST_GUARD, "base..HEAD", "--repo", armDir], { encoding: "utf8" });
  const gamingFlags = tg.status === 1;
  // size: lines the agent touched
  const ds = spawnSync("git", ["-C", armDir, "diff", "--shortstat", "base", "HEAD"], { encoding: "utf8" });
  const lines = ((ds.stdout || "").match(/(\d+) insertion.*?(\d+) deletion|(\d+) insertion|(\d+) deletion/) ? ds.stdout.trim() : "0");
  const success = verifierPass === true && suiteGreen && !gamingFlags;
  return { verifierPass, suiteGreen, suiteN, gamingFlags, diff: (ds.stdout || "").trim() || "no change", success };
}

function verify() {
  const runsRoot = arg("--runs");
  if (!runsRoot) usage("verify needs --runs <root>");
  const python = arg("--python", "python");
  const tasks = discoverTasks();
  const rows = [];
  for (const task of tasks) {
    const taskRunDir = path.join(runsRoot, task.name);
    if (!fs.existsSync(taskRunDir)) continue;
    const arms = fs.readdirSync(taskRunDir, { withFileTypes: true }).filter((e) => e.isDirectory()).map((e) => e.name);
    for (const arm of arms) {
      const armDir = path.join(taskRunDir, arm);
      if (!fs.existsSync(path.join(armDir, ".git"))) continue;
      rows.push({ task: task.name, arm, ...judgeArm(task, armDir, python) });
    }
  }
  if (!rows.length) usage("no arm workdirs found under " + runsRoot + " (expected <root>/<task>/<arm>/)");

  if (hasFlag("--json")) {
    console.log(JSON.stringify(rows, null, 2));
    return;
  }
  const mark = (b) => (b === true ? "✅" : b === false ? "❌" : "—");
  console.log("## A/B result table  (regenerated by `node eval/run.js verify`)\n");
  console.log("| Task | Arm | Verifier | Suite | Gaming | Diff | Success |");
  console.log("|---|---|---|---|---|---|---|");
  for (const r of rows) {
    console.log(
      `| ${r.task} | ${r.arm} | ${mark(r.verifierPass)} | ${r.suiteGreen ? "✅ " + r.suiteN : "❌"} | ${r.gamingFlags ? "⚠️ flags" : "clean"} | ${r.diff.replace(/\|/g, "/")} | ${r.success ? "✅" : "❌"} |`
    );
  }
  console.log("\nSuccess = arm-independent verifier green AND full suite green AND no unjustified gaming flag.");
  console.log("Cost/token metrics come from each arm's agent-run log, not this deterministic pass.");
}

const cmd = process.argv[2];
if (cmd === "verify") verify();
else usage("unknown command: " + (cmd || "(none)") + " — expected: verify --runs <root> [--python <interp>] [--json]");
